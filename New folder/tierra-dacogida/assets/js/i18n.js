  getLang() {
    const stored = localStorage.getItem('tda-lang');
    if (stored === 'en' || stored === 'es') {
      return stored;
    }
    const cookie = document.cookie.match(/(?:^|;\s*)tda_lang=(en|es)(?:;|$)/);
    if (cookie) {
      return cookie[1];
    }
    return this.defaultLang;
  },

  setLang(lang) {
    const l = lang === 'en' ? 'en' : 'es';
    localStorage.setItem('tda-lang', l);
    document.cookie = 'tda_lang=' + l + ';path=/;max-age=31536000;SameSite=Lax';
    document.documentElement.lang = l === 'en' ? 'en' : 'es';
    document.documentElement.setAttribute('data-lang', l);
    return l;
  },

  t(key, lang) {
    const l = lang || this.getLang();
    const parts = key.split('.');
    let val = this.translations[l];
    for (const p of parts) {
      if (!val || val[p] === undefined) return null;
      val = val[p];
    }
    return val;
  },

  buildLexicon(fromLang, toLang) {
    const map = new Map();
    const walk = (from, to) => {
      if (typeof from === 'string' && typeof to === 'string') {
        if (from && to && from !== to) {
          map.set(from.trim(), to);
        }
        return;
      }
      if (!from || !to || typeof from !== 'object' || typeof to !== 'object') {
        return;
      }
      Object.keys(from).forEach((key) => {
        if (Object.prototype.hasOwnProperty.call(to, key)) {
          walk(from[key], to[key]);
        }
      });
    };
    walk(this.translations[fromLang], this.translations[toLang]);
    return map;
  },

