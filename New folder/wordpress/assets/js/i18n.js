  getLang() {
    const stored = localStorage.getItem('tda-lang');
    return stored === 'en' ? 'en' : this.defaultLang;
  },

  t(key, lang) {
    const l = lang || this.getLang();
    const parts = key.split('.');
    let val = this.translations[l];
    for (const p of parts) {
      if (!val || val[p] === undefined) return null;
      val = val[p];
    }
    return val;
  },

  apply(lang) {
    const l = lang || this.getLang();
    localStorage.setItem('tda-lang', l);
    document.documentElement.lang = l;

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const text = this.t(el.dataset.i18n, l);
      if (text !== null) el.textContent = text;
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const text = this.t(el.dataset.i18nHtml, l);
      if (text !== null) el.innerHTML = text;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const text = this.t(el.dataset.i18nPlaceholder, l);
      if (text !== null) el.placeholder = text;
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
      const text = this.t(el.dataset.i18nAlt, l);
      if (text !== null) el.alt = text;
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const text = this.t(el.dataset.i18nAria, l);
      if (text !== null) el.setAttribute('aria-label', text);
    });

    const page = document.body.dataset.page;
    if (page) {
      const meta = this.t(`meta.${page}`, l);
      if (meta) {
        document.title = meta.title;
        const desc = document.querySelector('meta[name="description"]');
        if (desc) desc.content = meta.description;
      }
    }

    document.querySelectorAll('.lang-switcher__btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === l);
      btn.setAttribute('aria-pressed', btn.dataset.lang === l);
    });

    if (typeof Theme !== 'undefined') Theme.updateAria();
  },

  init() {
    this.apply(this.getLang());
    document.querySelectorAll('.lang-switcher__btn').forEach(btn => {
      btn.addEventListener('click', () => {
        if (btn.dataset.lang !== this.getLang()) {
          this.apply(btn.dataset.lang);
        }
      });
    });
  }
